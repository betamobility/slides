// The splice tool's copy of the scene library's reading (2026-10-13-2236
// plan, U12, KTD11). The plugin may import nothing outside
// plugins/beta-slides/, so instead of restating the gallery's rules (which
// drifted: Codex U12 round 1), this bundles the gallery's own pure module,
// slides/src/beta/libraryread.ts with what it imports, into one file with no
// imports at all:
//
//   plugins/beta-slides/scripts/lib/library-core.mjs   GENERATED, committed
//
//   node scripts/build-beta-plugin-library.mjs           write it
//   node scripts/build-beta-plugin-library.mjs --check   fail when it is stale (CI)

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const entry = join(root, 'slides', 'src', 'beta', 'libraryread.ts')
const out = join(root, 'plugins', 'beta-slides', 'scripts', 'lib', 'library-core.mjs')
const { buildSync } = createRequire(join(root, 'slides', 'package.json'))('esbuild')

const HEADER = `// GENERATED by scripts/build-beta-plugin-library.mjs from slides/src/beta/libraryread.ts.
// Do not edit: change the source and run the script. CI fails when this copy is stale.
// SPDX-License-Identifier: MIT
// Copyright (c) 2026 The Bento authors
`

export function bundle() {
  const r = buildSync({
    entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'neutral',
    target: 'es2022', legalComments: 'none', charset: 'utf8', logLevel: 'silent',
  })
  const code = r.outputFiles[0].text
  // the plugin's own rule (scripts/test-beta-splice.ts, KTD11): no import of anything
  if (/^\s*import\s|\bimport\(|\brequire\(/m.test(code)) throw new Error('the bundle imports something; the plugin may not')
  return HEADER + code
}

const want = bundle()
if (process.argv.includes('--check')) {
  const have = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (have !== want) {
    console.error(`✗ ${out.slice(root.length + 1)} is stale; run node scripts/build-beta-plugin-library.mjs`)
    process.exit(1)
  }
  console.log(`${out.slice(root.length + 1)} is current (${Buffer.byteLength(want)} bytes)`)
} else {
  writeFileSync(out, want)
  console.log(`wrote ${out.slice(root.length + 1)} (${Buffer.byteLength(want)} bytes)`)
}
