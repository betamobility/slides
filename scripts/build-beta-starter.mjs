// Generate slides/src/starter/beta.generated.ts, the deck a bare Beta shell
// boots with (replaces upstream's showcase, which stays in the tree for the
// merge). Re-run after beta/theme.json or scripts/lib/beta-layouts.mjs change;
// `--check` fails when the committed file is stale (CI runs it).
//
//   node scripts/build-beta-starter.mjs [--check]

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { betaStarter } from './lib/beta-layouts.mjs'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const out = join(root, 'slides/src/starter/beta.generated.ts')
const fragment = JSON.parse(readFileSync(join(root, 'beta/theme.json'), 'utf8'))
const doc = betaStarter(fragment)
if ('docId' in doc || 'collab' in doc || doc.template) throw new Error('the starter must carry no docId, collab or template flag')
// JSON as a string constant: smaller in the bundle than an object literal, and
// `<` escaped so the shell can never carry a literal </script> (hard rule 1).
const json = JSON.stringify(doc).replace(/</g, '\\u003c')
const body = `// GENERATED by scripts/build-beta-starter.mjs from beta/theme.json and
// scripts/lib/beta-layouts.mjs. Do not edit; re-run the generator.
// SPDX-License-Identifier: MIT
// Copyright (c) 2026 Beta Mobility
export const BETA_STARTER_JSON = ${JSON.stringify(json)}
`
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== body) { console.error(`✗ ${out} is stale: run node scripts/build-beta-starter.mjs`); process.exit(1) }
  console.log('beta starter is current')
} else {
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, body)
  console.log(`beta starter → ${out} (${Math.round(body.length / 1024)} KB, ${doc.slides.length} slides)`)
}
